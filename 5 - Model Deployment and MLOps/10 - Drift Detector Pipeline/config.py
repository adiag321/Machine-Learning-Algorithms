# -*- coding: utf-8 -*-
"""
config.py — Central configuration and logging setup for the Drift Detector Pipeline.

Edit paths and thresholds here. All other modules import from this file.
"""

import logging
import os
from logging.handlers import RotatingFileHandler

# ── Root paths ─────────────────────────────────────────────────────────────
_BASE    = os.path.dirname(__file__)                          # drift_detector/
_ML_ROOT = os.path.abspath(os.path.join(_BASE, "../../.."))  # Machine Learning Algorithms/

# ── Data paths ─────────────────────────────────────────────────────────────
# Generated by create_drift_datasets.py — run that script once before using the pipeline
REFERENCE_DATA_PATH: str = os.path.join(_ML_ROOT, "Datasets", "Drift_Detection", "reference_data.csv")
CURRENT_DATA_PATH:   str = os.path.join(_ML_ROOT, "Datasets", "Drift_Detection", "current_data.csv")

TARGET_COLUMN: str       = "Churn"   # binary label column (must be 0/1 or Yes/No)
TIMESTAMP_COL: str       = None      # set to a date column to enable batch trend analysis

# ── Drift thresholds ────────────────────────────────────────────────────────
# KS Test — p < threshold indicates statistically significant distribution shift
KS_P_THRESHOLD:           float = 0.05

# Chi-Squared Test — p < threshold indicates category proportion shift
CHI2_P_THRESHOLD:         float = 0.05

# PSI — industry standard: < 0.10 stable | 0.10–0.20 warning | > 0.20 critical
PSI_WARNING_THRESHOLD:    float = 0.10
PSI_CRITICAL_THRESHOLD:   float = 0.20
PSI_BINS:                 int   = 10

# JS Divergence — bounded [0,1]; > 0.10 indicates meaningful distribution difference
JS_DIVERGENCE_THRESHOLD:  float = 0.10

# DDM — flags concept drift when current error rate deviates by N std devs above reference
DDM_WARNING_LEVEL:        float = 2.0
DDM_ALERT_LEVEL:          float = 3.0

# Multivariate score — % of features drifted to classify overall pipeline severity
MULTIVARIATE_WARNING_PCT:  float = 0.20
MULTIVARIATE_CRITICAL_PCT: float = 0.50

# ── Output settings ─────────────────────────────────────────────────────────
OUTPUT_DIR:        str  = os.path.join(_BASE, "drift_reports")
SAVE_CSV_REPORT:   bool = True
SAVE_JSON_REPORT:  bool = True
SAVE_HTML_REPORT:  bool = True
SAVE_PLOTS:        bool = True
MAX_PLOT_FEATURES: int  = 10   # plot top N most drifted features (by JS score)

RANDOM_STATE: int = 42

# ── Logging setup ───────────────────────────────────────────────────────────
os.makedirs(OUTPUT_DIR, exist_ok=True)


def get_logger(name: str = "drift_detector") -> logging.Logger:
    """Returns a configured logger (console: INFO, rotating file: DEBUG)."""
    logger = logging.getLogger(name)
    if logger.handlers:
        return logger  # prevent duplicate handlers on re-import

    logger.setLevel(logging.DEBUG)

    fmt = logging.Formatter(
        "%(asctime)s | %(levelname)-8s | %(name)s | %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )

    # Console handler — INFO and above for operator visibility
    ch = logging.StreamHandler()
    ch.setLevel(logging.INFO)
    ch.setFormatter(fmt)

    # Rotating file handler — DEBUG and above for full audit trail
    fh = RotatingFileHandler(
        os.path.join(OUTPUT_DIR, "drift_detector.log"),
        maxBytes=2 * 1024 * 1024,
        backupCount=3,
    )
    fh.setLevel(logging.DEBUG)
    fh.setFormatter(fmt)

    logger.addHandler(ch)
    logger.addHandler(fh)
    return logger
